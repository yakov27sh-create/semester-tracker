#!/usr/bin/env bash
# Concatenates supabase/schemas/*.sql (in numeric filename order) into
# supabase/migrations/0_init.sql, applies it to the local Supabase stack,
# and regenerates the TypeScript client types from the result.
# Note: the underscore (not a dot) before "init" is required by the Supabase
# CLI's migration filename pattern (<prefix>_name.sql) — a dot there causes
# `supabase db reset`/`migration up` to silently skip the file.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/.." && pwd)"
schemas_dir="$script_dir/schemas"
output_file="$script_dir/migrations/0_init.sql"
types_targets=(
  "$script_dir/DatabaseTypes.ts"
  "$repo_root/web2/src/shared/DatabaseTypes.ts"
)

mkdir -p "$(dirname "$output_file")"

mapfile -t files < <(find "$schemas_dir" -maxdepth 1 -type f -name '*.sql' -printf '%f\n' | sort -t. -k1,1n)

if [ "${#files[@]}" -eq 0 ]; then
  echo "No .sql files found in $schemas_dir" >&2
  exit 1
fi

{
  echo "-- Generated by combine-schemas.sh. Do not edit directly."
  echo "-- Source: supabase/schemas/*.sql"
  echo
  for f in "${files[@]}"; do
    echo "-- ==== $f ===="
    cat "$schemas_dir/$f"
    echo
  done
} > "$output_file"

echo "Wrote $(basename "$output_file") from ${#files[@]} file(s): ${files[*]}"

echo "Resetting local database..."
supabase db reset

echo "Generating TypeScript types..."
for target in "${types_targets[@]}"; do
  mkdir -p "$(dirname "$target")"
  supabase gen types typescript --local > "$target"
  echo "Wrote $target"
done
